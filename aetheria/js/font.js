/* decoded to arrays of row-bitmasks once */
const FONT = {};
for (const ch in FONT_SRC) {
  FONT[ch] = FONT_SRC[ch].split(',').map(r => parseInt(r, 2));
}
const GLYPH_W = 5, GLYPH_H = 7;

function glyphFor(ch) {
  return FONT[ch] || FONT[ch.toUpperCase()] || FONT['?'];
}

/* width of a string in pixels at a given scale */
function textWidth(str, scale) {
  scale = scale || 1;
  return str.length ? (str.length * (GLYPH_W + 1) - 1) * scale : 0;
}

/* Draw text. `shadow` puts a hard drop-shadow behind it, which is what keeps
   pixel type readable on a busy background. */
function drawText(c, x, y, str, col, scale, shadow) {
  scale = scale || 1;
  x = Math.round(x); y = Math.round(y);
  const step = (GLYPH_W + 1) * scale;
  if (shadow) {
    for (let i = 0; i < str.length; i++) drawGlyph(c, x + i * step + scale, y + scale, str[i], shadow, scale);
  }
  for (let i = 0; i < str.length; i++) drawGlyph(c, x + i * step, y, str[i], col, scale);
  return str.length * step - scale;
}

function drawGlyph(c, x, y, ch, col, scale) {
  const g = glyphFor(ch);
  if (!g) return;
  c.fillStyle = col;
  for (let r = 0; r < GLYPH_H; r++) {
    const bits = g[r];
    if (!bits) continue;
    let run = 0, runStart = 0;
    for (let b = 0; b < GLYPH_W; b++) {
      const on = (bits >> (GLYPH_W - 1 - b)) & 1;
      if (on) { if (!run) runStart = b; run++; }
      else if (run) { c.fillRect(x + runStart * scale, y + r * scale, run * scale, scale); run = 0; }
    }
    if (run) c.fillRect(x + runStart * scale, y + r * scale, run * scale, scale);
  }
}

/* greedy word wrap to a pixel width */
function wrapText(str, maxW, scale) {
  scale = scale || 1;
  const words = String(str).split(' ');
  const lines = [];
  let line = '';
  for (const w of words) {
    const test = line ? line + ' ' + w : w;
    if (textWidth(test, scale) > maxW && line) { lines.push(line); line = w; }
    else line = test;
  }
  if (line) lines.push(line);
  return lines;
}

function drawTextCentered(c, cx, y, str, col, scale, shadow) {
  drawText(c, cx - textWidth(str, scale) / 2, y, str, col, scale, shadow);
}

window.FONT_API = { FONT, GLYPH_W, GLYPH_H, textWidth, drawText, drawGlyph, wrapText, drawTextCentered };
